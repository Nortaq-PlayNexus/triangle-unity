using System.Collections.Generic;
using Triangle.Core;
using Triangle.Dream;
using UnityEngine;

namespace Triangle.World
{
    /// <summary>
    /// Procedurally constructs the underground station - the Phase 2 environment.
    /// Fluorescent-lit platforms, dark tracks, a wrong train, Platform 12 signage.
    ///
    /// Port of ATriangleStationBuilder. As with the bedroom, the Unreal version
    /// authored in centimetres on a Z-up axis 5000 cm above the template landscape;
    /// this is authored directly in metres with Y up. The 700 x 400 x 350 Unreal
    /// half-extents become a 14 x 8 x 3.5 m tunnel.
    ///
    /// Built from runtime basic shapes so the slice runs with zero content assets.
    /// </summary>
    [DisallowMultipleComponent]
    public class TriangleStationBuilder : MonoBehaviour
    {
        [Header("Station dimensions (metres)")]
        [SerializeField] private float stationHalfX = 4.0f;   // was Unreal Y half-extent 400
        [SerializeField] private float stationHalfZ = 7.0f;   // was Unreal X half-extent 700
        [SerializeField] private float stationHeight = 3.5f;  // was Unreal 350
        [SerializeField] private float platformHeight = 1.2f; // was Unreal 120

        private const float WallThickness = 0.2f;
        private const float TrackGap = 1.5f; // was Unreal 150 half-gap between platform edge and track

        /// <summary>
        /// Centre line of a platform, in metres. The track bed occupies the open band
        /// between -TrackGap and +TrackGap, so anything the player is meant to stand
        /// on has to sit outside that.
        /// </summary>
        private float PlatformCentreX => (stationHalfX + TrackGap) * 0.5f;

        /// <summary>
        /// Cool, dirty concrete tones. As with the bedroom, a single shared bright grey
        /// made every surface read as the same flat mass; separating platform, wall,
        /// ceiling and track gives the fluorescent strips something to model.
        /// </summary>
        private static readonly Color ConcreteColor = new Color(0.150f, 0.152f, 0.150f);
        private static readonly Color PlatformColor = new Color(0.205f, 0.200f, 0.190f);
        private static readonly Color CeilingColor = new Color(0.085f, 0.088f, 0.092f);
        private static readonly Color WallColor = new Color(0.125f, 0.128f, 0.130f);
        private static readonly Color EndWallColor = new Color(0.055f, 0.058f, 0.062f);
        private static readonly Color TrackColor = new Color(0.040f, 0.042f, 0.046f);
        private static readonly Color SleeperColor = new Color(0.070f, 0.060f, 0.050f);
        private static readonly Color SafetyLineColor = new Color(0.330f, 0.280f, 0.060f);
        private static readonly Color BenchColor = new Color(0.105f, 0.085f, 0.060f);

        private readonly List<GameObject> _spawned = new List<GameObject>();

        private Transform _dreamStart;
        private Vector3 _platform12Location;

        /// <summary>
        /// The fluorescent strip cookie, shared by all four fixtures.
        ///
        /// One texture rather than four: a cookie atlas packs them anyway, and four
        /// identical copies would be four times the memory for no benefit.
        /// </summary>
        private Texture2D _stripCookie;

        public IReadOnlyList<GameObject> SpawnedPieces => _spawned;

        /// <summary>The start generated by this builder, if it has finished assembling.</summary>
        public Transform DreamStart => _dreamStart;

        /// <summary>World position of the Platform 12 marker the Director watches.</summary>
        public Vector3 Platform12Location => _platform12Location;

        /// <summary>
        /// Assembles in Awake, not Start, so the station is complete the moment the
        /// environment flow creates it. See the note on TriangleRoomBuilder.
        /// </summary>
        private void Awake()
        {
            // Built before the fixtures, which reference it. 4:1 aspect because the tube is
            // four times longer than it is wide, and a square cookie would project a square
            // pool onto the platform.
            _stripCookie = TriangleLighting.StripCookie(128, 0.9f, 0.18f);

            BuildShell();
            BuildPlatforms();
            BuildTiles();
            BuildTracks();
            BuildFluorescentLights();
            BuildVentilation();
            BuildBenches();
            BuildSafetyLights();
            BuildPlatform12Marker();
            BuildTrain();
            BuildCornerPoint();
            BuildLighting();
            BuildProbes();

            // Player spawn on the right-hand platform, facing the tracks across the bed.
            // The previous value was x = 0, which is the middle of the track gap: the
            // pawn was dropped onto the rails, contradicting the comment and the test
            // that claims to check for it.
            GameObject start = Track(new GameObject("DreamStart"));
            start.transform.position = new Vector3(PlatformCentreX, platformHeight + 1.0f, 2.5f);
            start.transform.rotation = Quaternion.Euler(0f, 270f, 0f);
            start.tag = "DreamStart";
            _dreamStart = start.transform;

            TriangleLog.Log("Underground station assembled.");
        }

        private void OnDestroy()
        {
            // The station is assembled at runtime. Destroy every piece explicitly so
            // replacing the environment cannot leave orphaned lights, props, or starts.
            for (int i = _spawned.Count - 1; i >= 0; i--)
            {
                if (_spawned[i] != null)
                {
                    Destroy(_spawned[i]);
                }
            }

            _spawned.Clear();
            _dreamStart = null;

            // The strip cookie is a Texture2D rather than a scene object, so destroying the
            // fixtures that reference it does not reclaim it. Without this every station
            // rebuild would leak another one.
            if (_stripCookie != null)
            {
                if (Application.isPlaying)
                {
                    Destroy(_stripCookie);
                }
                else
                {
                    DestroyImmediate(_stripCookie);
                }

                _stripCookie = null;
            }
        }

        private GameObject Track(GameObject go)
        {
            _spawned.Add(go);
            return go;
        }

        /// <summary>
        /// Spawns a box with softened edges and records it for teardown. Position in metres.
        /// </summary>
        /// <remarks>
        /// The bevel mesh rather than Unity's cube. A station is the worst case for hard
        /// edges: long unbroken runs of concrete meeting at 90 degrees, with nothing else in
        /// frame. The highlight that runs along each corner edge is most of what tells the
        /// eye how long the tunnel is, and a perfect cube has no highlight there at all.
        /// </remarks>
        private GameObject AddBox(Vector3 position, Vector3 scale, Quaternion? rotation = null, Color? color = null,
            TriangleProceduralTextures.SurfaceKind? surface = null, float tiling = 1f)
        {
            GameObject box = TriangleShapes.CreateShape("StationPiece", TriangleShapes.BevelBoxMesh, transform);
            box.transform.position = position;
            box.transform.rotation = rotation ?? Quaternion.identity;
            box.transform.localScale = scale;
            Track(box);

            box.GetComponent<MeshRenderer>().sharedMaterial =
                TriangleShapes.GetMaterial(color ?? ConcreteColor, surface, tiling);
            box.AddComponent<BoxCollider>().size = Vector3.one;
            return box;
        }

        /// <summary>
        /// Spawns a decorative box with no collider, for anything flush with a surface the
        /// player cannot pass through anyway.
        /// </summary>
        private GameObject AddTrim(Vector3 position, Vector3 scale, Color color,
            TriangleProceduralTextures.SurfaceKind? surface = null, float tiling = 1f,
            float smoothness = 0.30f, Quaternion? rotation = null)
        {
            GameObject box = AddBox(position, scale, rotation, color, surface, tiling);
            box.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetSmoothMaterial(color, smoothness);

            BoxCollider collider = box.GetComponent<BoxCollider>();
            if (collider != null)
            {
                collider.enabled = false;
            }

            return box;
        }

        private void BuildShell()
        {
            // Floor - concrete-grey, slightly warm.
            AddBox(new Vector3(0f, -0.1f, 0f), new Vector3(stationHalfX * 2f, 0.2f, stationHalfZ * 2f),
                color: ConcreteColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.7f);

            // Ceiling - low, oppressive.
            AddBox(new Vector3(0f, stationHeight + 0.1f, 0f), new Vector3(stationHalfX * 2f, 0.15f, stationHalfZ * 2f),
                color: CeilingColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.5f);

            // Side walls.
            AddBox(new Vector3(-stationHalfX, stationHeight * 0.5f, 0f), new Vector3(WallThickness, stationHeight, stationHalfZ * 2f),
                color: WallColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.6f);
            AddBox(new Vector3(stationHalfX, stationHeight * 0.5f, 0f), new Vector3(WallThickness, stationHeight, stationHalfZ * 2f),
                color: WallColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.6f);

            // End wall (far end - dark, no exit).
            AddBox(new Vector3(0f, stationHeight * 0.5f, -stationHalfZ), new Vector3(stationHalfX * 2f, stationHeight, WallThickness),
                color: EndWallColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.6f);

            // Near end wall. Without it the tunnel simply stopped at z = +stationHalfZ
            // and the player could walk straight off the end of the world.
            AddBox(new Vector3(0f, stationHeight * 0.5f, stationHalfZ), new Vector3(stationHalfX * 2f, stationHeight, WallThickness),
                color: EndWallColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.6f);
        }

        private void BuildPlatforms()
        {
            // Raised blocks either side of the track bed.
            float platformDepth = (stationHalfX - TrackGap) * 0.5f;
            float platformCentreX = PlatformCentreX;

            AddBox(new Vector3(-platformCentreX, platformHeight * 0.5f, 0f),
                new Vector3(platformDepth, platformHeight, stationHalfZ * 2f),
                color: PlatformColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.8f);
            AddBox(new Vector3(platformCentreX, platformHeight * 0.5f, 0f),
                new Vector3(platformDepth, platformHeight, stationHalfZ * 2f),
                color: PlatformColor, surface: TriangleProceduralTextures.SurfaceKind.Concrete, tiling: 0.8f);

            // Platform surface markings - thin lighter strips near the edge. These are
            // paint: no collider, so they cannot snag the pawn or the interaction scan.
            GameObject leftLine = AddBox(new Vector3(-(stationHalfX - 0.05f), platformHeight + 0.01f, 0f),
                new Vector3(0.05f, 0.1f, stationHalfZ * 2f - 0.4f), color: SafetyLineColor);
            leftLine.GetComponent<BoxCollider>().enabled = false;
            GameObject rightLine = AddBox(new Vector3(stationHalfX - 0.05f, platformHeight + 0.01f, 0f),
                new Vector3(0.05f, 0.1f, stationHalfZ * 2f - 0.4f), color: SafetyLineColor);
            rightLine.GetComponent<BoxCollider>().enabled = false;
        }

        /// <summary>
        /// Platform edge nosing and a tactile strip.
        ///
        /// A station platform's most legible feature is its edge: a light stone lip with a
        /// row of bumps you are meant to feel rather than see. Without it the platforms are
        /// two grey blocks either side of a trench, and the player has no cue where standing
        /// one step too far would mean falling onto the track bed.
        ///
        /// Cheap - the strip is one emissive-tinted box and the nosing is four.
        /// </summary>
        private void BuildTiles()
        {
            float edgeX = stationHalfX - 0.06f;

            // Nosing: a lighter band along the platform edge, proud of the surface.
            AddTrim(new Vector3(-edgeX, platformHeight + 0.012f, 0f),
                new Vector3(0.12f, 0.024f, stationHalfZ * 2f - 0.4f),
                new Color(0.245f, 0.242f, 0.232f), TriangleProceduralTextures.SurfaceKind.Concrete, 1.6f, 0.34f);

            AddTrim(new Vector3(edgeX, platformHeight + 0.012f, 0f),
                new Vector3(0.12f, 0.024f, stationHalfZ * 2f - 0.4f),
                new Color(0.245f, 0.242f, 0.232f), TriangleProceduralTextures.SurfaceKind.Concrete, 1.6f, 0.34f);

            // Tactile warning strip, just inboard of the nosing. Slightly emissive so it
            // catches the fluorescents from a distance - which is the whole point of it.
            AddTrim(new Vector3(-(edgeX - 0.20f), platformHeight + 0.016f, 0f),
                new Vector3(0.26f, 0.020f, stationHalfZ * 2f - 0.5f),
                new Color(0.330f, 0.290f, 0.115f), null, 1f, 0.20f);

            AddTrim(new Vector3(edgeX - 0.20f, platformHeight + 0.016f, 0f),
                new Vector3(0.26f, 0.020f, stationHalfZ * 2f - 0.5f),
                new Color(0.330f, 0.290f, 0.115f), null, 1f, 0.20f);

            // Wall dado: a band of a different value along the lower wall. This is what gives
            // a tunnel a horizon line, and without one the walls read as an undifferentiated
            // grey field with no sense of how far away they are.
            float dadoHeight = 1.1f;
            AddTrim(new Vector3(-stationHalfX + WallThickness * 0.5f + 0.012f, dadoHeight * 0.5f, 0f),
                new Vector3(0.024f, dadoHeight, stationHalfZ * 2f),
                new Color(0.098f, 0.100f, 0.104f), null, 1f, 0.26f);

            AddTrim(new Vector3(stationHalfX - WallThickness * 0.5f - 0.012f, dadoHeight * 0.5f, 0f),
                new Vector3(0.024f, dadoHeight, stationHalfZ * 2f),
                new Color(0.098f, 0.100f, 0.104f), null, 1f, 0.26f);

            // A capping rail on the dado, the one horizontal line in the tunnel that the eye
            // can use to judge depth.
            for (int side = 0; side < 2; side++)
            {
                float x = side == 0
                    ? -stationHalfX + WallThickness * 0.5f + 0.020f
                    : stationHalfX - WallThickness * 0.5f - 0.020f;

                AddTrim(new Vector3(x, dadoHeight, 0f),
                    new Vector3(0.030f, 0.035f, stationHalfZ * 2f),
                    new Color(0.165f, 0.168f, 0.172f), null, 1f, 0.40f);
            }
        }

        private void BuildTracks()
        {
            // Two dark strips for the track bed between platforms.
            AddBox(new Vector3(-1.5f, 0.02f, 0f), new Vector3(0.3f, 0.1f, stationHalfZ * 2f), color: TrackColor);
            AddBox(new Vector3(1.5f, 0.02f, 0f), new Vector3(0.3f, 0.1f, stationHalfZ * 2f), color: TrackColor);

            // Sleepers - thin dark boxes under the tracks. Purely decorative, and the
            // track bed already has a floor under it, so they carry no collider. Giving
            // ~18 of them one only inflated the interaction overlap set.
            for (float z = -stationHalfZ + 0.8f; z < stationHalfZ - 0.8f; z += 0.7f)
            {
                GameObject sleeper = AddBox(new Vector3(0f, 0.01f, z), new Vector3(stationHalfX * 2f, 0.08f, 0.4f),
                    color: SleeperColor, surface: TriangleProceduralTextures.SurfaceKind.Wood, tiling: 2.0f);
                sleeper.GetComponent<BoxCollider>().enabled = false;
            }
        }

        private void BuildFluorescentLights()
        {
            // Four long fluorescent strips along the ceiling - cold, clinical.
            //
            // Built as a fixture housing with a separate emissive tube inside it, plus a spot
            // aimed down with a strip cookie. The previous version was a white box with a
            // point light beside it, which reads as a light bulb hanging in a tunnel: a point
            // light throws in every direction including up into the ceiling, and produces a
            // round pool rather than the long band a tube actually casts.
            for (int i = 0; i < 4; i++)
            {
                float x = -3.0f + i * 2.0f;
                // Not const: stationHeight is a serialized field, so its value is not a compile-time
                // constant even though it never changes at runtime.
                float fixtureY = stationHeight - 0.16f;

                // Housing, with a channel that the tube sits down inside. The housing is
                // what casts the tube's shadow onto the ceiling above it.
                AddTrim(new Vector3(x, fixtureY + 0.07f, 0f),
                    new Vector3(0.20f, 0.10f, 4.2f), new Color(0.115f, 0.120f, 0.128f), null, 1f, 0.36f);

                // The tube. Emissive well above 1.0 so bloom catches it, and unshadowed
                // because a light source casting a shadow reads as an error.
                GameObject tube = AddTrim(new Vector3(x, fixtureY, 0f),
                    new Vector3(0.11f, 0.075f, 4.0f), Color.white);
                tube.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetEmissiveMaterial(
                    new Color(0.86f, 0.92f, 0.90f), 4.5f);

                // Two end caps, because a bare white slab with visible ends is the giveaway
                // that the "tube" is a box.
                for (int end = 0; end < 2; end++)
                {
                    float z = end == 0 ? -2.02f : 2.02f;
                    AddTrim(new Vector3(x, fixtureY, z),
                        new Vector3(0.14f, 0.10f, 0.06f), new Color(0.10f, 0.105f, 0.11f),
                        null, 1f, 0.42f);
                }

                // The light itself: a spot aimed down the tunnel axis.
                var lightObject = Track(new GameObject("Fluorescent"));
                lightObject.transform.SetParent(transform, false);
                lightObject.transform.position = new Vector3(x, fixtureY - 0.06f, 0f);
                lightObject.transform.rotation = Quaternion.Euler(90f, 0f, 0f);

                // Only every other fixture shadows. Four shadow-casting lights in a tunnel
                // this enclosed cost real time and buy almost nothing, because the shadows
                // they would cast land on each other.
                Light light = TriangleLighting.Create(lightObject, LightType.Spot,
                    new Color(0.80f, 0.88f, 0.86f), 2.6f, 9f, Vector3.zero,
                    TriangleLighting.LayerKey, i % 2 == 0 ? LightShadows.Soft : LightShadows.None);

                light.spotAngle = 140f;
                light.innerSpotAngle = 55f;

                // The strip cookie. This is what makes the pool of light on the platform a
                // long band running down the tunnel instead of a circle, which is the single
                // most recognisable feature of a real station platform.
                light.cookie = _stripCookie;
            }
        }

        private void BuildVentilation()
        {
            // Two ducts running along the ceiling between the lights.
            AddBox(new Vector3(-2.0f, stationHeight - 0.08f, 0f), new Vector3(0.25f, 0.25f, stationHalfZ * 2f),
                color: ConcreteColor);
            AddBox(new Vector3(2.0f, stationHeight - 0.08f, 0f), new Vector3(0.25f, 0.25f, stationHalfZ * 2f),
                color: ConcreteColor);
        }

        private void BuildBenches()
        {
            // One bench on each platform, near the middle.
            AddBox(new Vector3(-3.0f, platformHeight + 0.2f, -2.3f), new Vector3(0.35f, 0.4f, 1.2f),
                color: BenchColor);
            AddBox(new Vector3(-3.0f, platformHeight + 0.4f, -2.3f), new Vector3(0.15f, 0.4f, 1.2f),
                color: BenchColor);

            AddBox(new Vector3(3.0f, platformHeight + 0.2f, 2.3f), new Vector3(0.35f, 0.4f, 1.2f),
                color: BenchColor);
            AddBox(new Vector3(3.0f, platformHeight + 0.4f, 2.3f), new Vector3(0.15f, 0.4f, 1.2f),
                color: BenchColor);
        }

        private void BuildSafetyLights()
        {
            // Four broad amber pools are enough to keep the platform edge readable.
            // The original 26 tiny point lights looked richer in theory but were a
            // poor trade on a GTX 1080's path. The name carries the x offset so the
            // hierarchy does not end up with four identically named lights.
            foreach (float x in new[] { -3.5f, 3.5f })
            {
                string side = x < 0f ? "Left" : "Right";
                AddLight($"Safety{side}{x:0.0}", new Vector3(x, platformHeight + 0.08f, -1.48f),
                    new Color(0.6f, 0.35f, 0.05f), 0.5f, 1.8f);
                AddLight($"Safety{side}{x:0.0}_Far", new Vector3(x, platformHeight + 0.08f, 1.48f),
                    new Color(0.6f, 0.35f, 0.05f), 0.5f, 1.8f);
            }
        }

        private void BuildPlatform12Marker()
        {
            // The sign stands on the left-hand platform rather than over the track bed,
            // and its post is a single run from the platform floor all the way up to the
            // panel. The previous version put a post at mid-height with nothing beneath
            // it, hanging in mid-air over the rails and clipping the near end wall.
            float signX = -PlatformCentreX;
            const float postTop = 1.75f;

            AddBox(new Vector3(signX, platformHeight + postTop * 0.5f, stationHalfZ - 1.2f),
                new Vector3(0.08f, postTop, 0.08f), color: new Color(0.25f, 0.25f, 0.25f));

            // The sign itself: thin across the platform, wide along it, and tall.
            float signY = platformHeight + postTop;
            float signZ = stationHalfZ - 1.2f;
            AddBox(new Vector3(signX, signY, signZ),
                new Vector3(0.06f, 0.6f, 1.2f), color: new Color(0.9f, 0.85f, 0.15f));

            // Basic shapes cannot show the number 12 without a texture or a font, so
            // the number is drawn as three small emissive bars on the sign face.
            BuildPlatformTwelveGlyph(new Vector3(signX + 0.04f, signY, signZ));

            _platform12Location = new Vector3(signX, signY, signZ);
        }

        /// <summary>
        /// Draws "12" from unlit emissive bars: a vertical stroke plus a diagonal and
        /// a foot for the 1, and a curved approximation from three strokes for the 2.
        /// Cheaper and more robust than shipping a font asset, and it survives the
        /// "no content assets" constraint the slice is built on.
        /// </summary>
        private void BuildPlatformTwelveGlyph(Vector3 signCentre)
        {
            var glyph = new Color(0.90f, 0.85f, 0.15f);
            var material = TriangleShapes.GetEmissiveMaterial(glyph, 1.4f);

            // "1" - a stem with a flag and a foot, sitting left of centre.
            AddGlyphBar(material, signCentre + new Vector3(0.035f, 0.12f, -0.30f), new Vector3(0.02f, 0.34f, 0.05f));
            AddGlyphBar(material, signCentre + new Vector3(0.005f, 0.22f, -0.30f), new Vector3(0.10f, 0.035f, 0.05f), Quaternion.Euler(0f, 0f, 35f));
            AddGlyphBar(material, signCentre + new Vector3(0.03f, -0.05f, -0.30f), new Vector3(0.16f, 0.035f, 0.05f));

            // "2" - top curve, diagonal, foot.
            AddGlyphBar(material, signCentre + new Vector3(0.035f, 0.28f, 0.26f), new Vector3(0.18f, 0.035f, 0.05f));
            AddGlyphBar(material, signCentre + new Vector3(0.13f, 0.17f, 0.26f), new Vector3(0.035f, 0.20f, 0.05f), Quaternion.Euler(0f, 0f, 18f));
            AddGlyphBar(material, signCentre + new Vector3(0.01f, 0.06f, 0.26f), new Vector3(0.035f, 0.24f, 0.05f), Quaternion.Euler(0f, 0f, -38f));
            AddGlyphBar(material, signCentre + new Vector3(0.035f, -0.05f, 0.26f), new Vector3(0.18f, 0.035f, 0.05f));
        }

        private void AddGlyphBar(Material material, Vector3 position, Vector3 scale, Quaternion? rotation = null)
        {
            GameObject bar = TriangleShapes.CreateShape("GlyphBar", TriangleShapes.Cube, transform);
            bar.transform.position = position;
            bar.transform.rotation = rotation ?? Quaternion.identity;
            bar.transform.localScale = scale;
            bar.GetComponent<MeshRenderer>().sharedMaterial = material;
            bar.GetComponent<MeshRenderer>().shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
            Track(bar);
        }

        private void BuildTrain()
        {
            GameObject train = Track(new GameObject("WrongTrain"));
            train.transform.SetParent(transform, true);
            train.transform.position = new Vector3(0.6f, 0f, 0f);
            train.tag = "WrongTrain";
            train.AddComponent<TriangleTrain>();
        }

        private void BuildCornerPoint()
        {
            // Upper corner of the far platform - where the Triangle first appears.
            Vector3 corner = new Vector3(-(stationHalfX - 0.6f), platformHeight + 0.1f, 3.6f);
            GameObject point = Track(new GameObject("TrianglePoint"));
            point.transform.SetParent(transform, true);
            point.transform.position = corner;
            TrianglePoint trianglePoint = point.AddComponent<TrianglePoint>();
            trianglePoint.ManifestId = "StationCorner";
        }

        private void BuildLighting()
        {
            // As in the bedroom, the atmosphere is declared through the owning
            // component rather than written straight into the global render settings.
            // The values are unchanged.
            GameObject atmosphereObject = Track(new GameObject("StationAtmosphere"));
            atmosphereObject.transform.SetParent(transform, false);

            var atmosphere = atmosphereObject.AddComponent<TriangleEnvironmentAtmosphere>();
            // Ambient is kept low so the fluorescents actually model the platforms
            // instead of flooding everything evenly.
            atmosphere.Ambient = UnityEngine.Rendering.AmbientMode.Trilight;
            atmosphere.SkyColor = new Color(0.13f, 0.15f, 0.18f);
            atmosphere.EquatorColor = new Color(0.05f, 0.055f, 0.065f);
            atmosphere.GroundColor = new Color(0.015f, 0.016f, 0.020f);
            atmosphere.Intensity = 0.18f;
            // Fog - thicker than the bedroom; underground, no breeze.
            atmosphere.FogEnabled = true;
            atmosphere.Fog = FogMode.ExponentialSquared;
            atmosphere.FogDensity = 0.045f;
            atmosphere.FogColor = new Color(0.022f, 0.026f, 0.034f);
            atmosphere.Apply();

            // Near-total darkness over the tracks.
            AddLight("TrackFill", new Vector3(0f, 1.0f, 0f), new Color(0.05f, 0.05f, 0.07f), 0.12f, 5f);
        }

        /// <summary>
        /// Places the station's reflection probe.
        ///
        /// Sized to the tunnel rather than the whole level, and positioned at the centre of
        /// the track bed so its box projection covers both platforms. A probe this long has
        /// a cubemap that cannot hold fine detail, which is fine here: what the platforms
        /// need reflected is the four bright tubes overhead, and those are large.
        /// </summary>
        private void BuildProbes()
        {
            var probe = TriangleLighting.CreateProbe(Track(new GameObject("StationReflectionProbe")),
                new Vector3(0f, stationHeight * 0.5f, 0f),
                new Vector3(stationHalfX * 2f - 0.4f, stationHeight - 0.3f, stationHalfZ * 2f - 0.4f));

            TriangleLighting.RefreshWhenSettled(probe, this);
        }

        private void AddLight(string lightName, Vector3 position, Color color, float intensity, float range,
            LightShadows shadows = LightShadows.None)
        {
            var lightObject = Track(new GameObject(lightName));
            lightObject.transform.SetParent(transform, true);

            TriangleLighting.Create(lightObject, LightType.Point, color, intensity, range, position,
                TriangleLighting.LayerFill, shadows);
        }
    }
