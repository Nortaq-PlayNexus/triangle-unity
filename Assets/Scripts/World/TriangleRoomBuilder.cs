using System.Collections.Generic;
using Triangle.Core;
using Triangle.Dream;
using Triangle.World;
using UnityEngine;

namespace Triangle.World
{
    /// <summary>
    /// Procedurally constructs the childhood bedroom - the slice's first playable
    /// dream environment - out of runtime basic shapes.
    ///
    /// Port of ATriangleRoomBuilder. The Unreal version authored the room in
    /// centimetres on a Z-up axis and had to sit it 5000 cm above the template
    /// landscape to avoid stray terrain collision; Unity has neither constraint, so
    /// the room is authored directly in metres with Y up. The authored dimensions
    /// are unchanged (410 x 310 x 300 Unreal half-extents become 8.2 x 6.2 x 3.0 m).
    ///
    /// Every piece is isolated here behind simple named helpers so that, when real
    /// assets arrive later, this class can be replaced by scene assembly without
    /// touching gameplay systems.
    /// </summary>
    [DisallowMultipleComponent]
    public class TriangleRoomBuilder : MonoBehaviour
    {
        [Header("Room dimensions (metres)")]
        [SerializeField] private float roomHalfX = 3.1f;   // was Unreal Y half-extent 310
        [SerializeField] private float roomHalfZ = 4.1f;   // was Unreal X half-extent 410
        [SerializeField] private float roomHeight = 3.0f;  // was Unreal 300

        private const float WallThickness = 0.2f;
        private const float DoorGapMinX = 1.2f;
        private const float DoorGapMaxX = 2.3f;
        private const float DoorGapHeight = 2.2f;

        private readonly List<GameObject> _spawned = new List<GameObject>();

        private Transform _dreamStart;
        private Vector3 _cornerLocation;

        /// <summary>Every piece spawned for this environment, for explicit teardown.</summary>
        public IReadOnlyList<GameObject> SpawnedPieces => _spawned;

        /// <summary>The start generated by this builder, if it has finished assembling.</summary>
        public Transform DreamStart => _dreamStart;

        /// <summary>World position of the upper-corner point the Dream Director watches.</summary>
        public Vector3 TriangleCornerLocation => _cornerLocation;

        /// <summary>
        /// Assembles in Awake, not Start.
        ///
        /// The environment flow creates this builder at runtime and immediately needs
        /// its DreamStart and its door in order to seat the player and subscribe the
        /// transition. Unity defers Start to the next frame but runs Awake synchronously
        /// from AddComponent, so building here is what makes the room exist by the time
        /// the flow returns.
        /// </summary>
        private void Awake()
        {
            _cornerLocation = new Vector3(roomHalfX * 0.95f, roomHeight * 0.97f, -roomHalfZ * 0.97f);

            BuildShell();
            BuildWindow();
            BuildBed();
            BuildDesk();
            BuildClock();
            BuildNotebook();
            BuildDoor();
            BuildCornerPoint();
            BuildLighting();

            // The player spawns centred in the room, facing the window-lit back wall
            // so the first thing on screen reads as a moonlit bedroom.
            GameObject start = Track(new GameObject("DreamStart"));
            start.transform.position = new Vector3(0f, 0.92f, 0f);
            start.transform.rotation = Quaternion.Euler(0f, 180f, 0f);
            start.tag = "DreamStart";
            _dreamStart = start.transform;

            TriangleLog.Log("Childhood bedroom assembled.");
        }

        private void OnDestroy()
        {
            // These objects are runtime pieces of the procedural environment rather
            // than scene assets. Tear them down explicitly when the builder is
            // replaced or the world is unloaded.
            for (int i = _spawned.Count - 1; i >= 0; i--)
            {
                if (_spawned[i] != null)
                {
                    Destroy(_spawned[i]);
                }
            }

            _spawned.Clear();
            _dreamStart = null;
        }

        private GameObject Track(GameObject go)
        {
            _spawned.Add(go);
            return go;
        }

        /// <summary>Spawns a plain box and records it for teardown. Position is in metres.</summary>
        private GameObject AddBox(Vector3 position, Vector3 scale, Quaternion? rotation = null)
        {
            GameObject box = Track(TriangleShapes.CreateShape("RoomPiece", TriangleShapes.Cube, transform));
            box.transform.SetParent(transform, true);
            box.transform.position = position;
            box.transform.rotation = rotation ?? Quaternion.identity;
            box.transform.localScale = scale;

            MeshRenderer renderer = box.GetComponent<MeshRenderer>();
            renderer.sharedMaterial = TriangleShapes.GetMaterial(new Color(0.42f, 0.40f, 0.38f));

            var collider = box.AddComponent<BoxCollider>();
            collider.size = Vector3.one;
            return box;
        }

        private void BuildShell()
        {
            // Floor / ceiling.
            AddBox(new Vector3(0f, -0.1f, 0f), new Vector3(roomHalfX * 2f, 0.2f, roomHalfZ * 2f));
            AddBox(new Vector3(0f, roomHeight + 0.1f, 0f), new Vector3(roomHalfX * 2f, 0.15f, roomHalfZ * 2f));

            // Back wall (Z negative) - has the window, built as a thin full wall plus
            // the window light source in BuildWindow().
            AddBox(new Vector3(0f, roomHeight * 0.5f, -roomHalfZ), new Vector3(roomHalfX * 2f, roomHeight, WallThickness));

            // Left / right walls.
            AddBox(new Vector3(-roomHalfX, roomHeight * 0.5f, 0f), new Vector3(WallThickness, roomHeight, roomHalfZ * 2f));
            AddBox(new Vector3(roomHalfX, roomHeight * 0.5f, 0f), new Vector3(WallThickness, roomHeight, roomHalfZ * 2f));

            // Front wall (Z positive) with the door gap.
            float leftWidth = DoorGapMinX + roomHalfX;
            AddBox(new Vector3((DoorGapMinX - roomHalfX) * 0.5f, roomHeight * 0.5f, roomHalfZ),
                new Vector3(leftWidth, roomHeight, WallThickness));

            float rightWidth = roomHalfX - DoorGapMaxX;
            AddBox(new Vector3((DoorGapMaxX + roomHalfX) * 0.5f, roomHeight * 0.5f, roomHalfZ),
                new Vector3(rightWidth, roomHeight, WallThickness));

            // Lintel above the gap.
            AddBox(new Vector3((DoorGapMinX + DoorGapMaxX) * 0.5f, (roomHeight + DoorGapHeight) * 0.5f, roomHalfZ),
                new Vector3(DoorGapMaxX - DoorGapMinX, roomHeight - DoorGapHeight, WallThickness));
        }

        private void BuildWindow()
        {
            // A pale panel on the back wall that reads as moonlight.
            GameObject window = AddBox(new Vector3(0f, 1.5f, -roomHalfZ - 0.02f), new Vector3(1.2f, 1.4f, 0.06f));
            window.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetEmissiveMaterial(
                new Color(0.55f, 0.68f, 0.95f), 0.9f);
            window.GetComponent<BoxCollider>().enabled = false;
        }

        private void BuildBed()
        {
            // Frame, mattress and pillow reads as a bed in the dark.
            AddBox(new Vector3(-2.2f, 0.15f, 1.5f), new Vector3(1.0f, 0.3f, 2.0f));
            AddBox(new Vector3(-2.2f, 0.42f, 1.5f), new Vector3(0.95f, 0.12f, 1.9f));
            AddBox(new Vector3(-2.32f, 0.53f, 0.6f), new Vector3(0.7f, 0.10f, 0.45f));
            // Headboard.
            AddBox(new Vector3(-2.2f, 0.55f, 2.52f), new Vector3(1.0f, 0.75f, 0.12f));
        }

        private void BuildDesk()
        {
            AddBox(new Vector3(2.0f, 0.55f, -0.8f), new Vector3(0.6f, 0.7f, 1.2f));
        }

        private void BuildClock()
        {
            // A deliberately ordinary bedroom clock, stopped at twelve. The motif can
            // now refer to something the player has actually seen in the room.
            Vector3 clockPosition = new Vector3(roomHalfX - 0.05f, 2.05f, -0.8f);
            GameObject clock = TriangleShapes.CreateShape("Clock", TriangleShapes.Cylinder, transform);
            clock.transform.SetParent(transform, true);
            clock.transform.position = clockPosition;
            // Unity's cylinder runs along Y; rotate it so the disc faces into the room.
            clock.transform.rotation = Quaternion.Euler(0f, 0f, 90f);
            clock.transform.localScale = new Vector3(0.04f, 0.68f, 0.68f);
            clock.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetMaterial(new Color(0.28f, 0.24f, 0.18f));
            Track(clock);

            // Both hands point to twelve; their different lengths remain readable at a
            // distance without requiring a texture or imported clock mesh.
            GameObject longHand = AddBox(new Vector3(roomHalfX - 0.10f, 2.31f, -0.8f), new Vector3(0.025f, 0.52f, 0.035f));
            longHand.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetMaterial(new Color(0.72f, 0.68f, 0.58f));
            longHand.GetComponent<BoxCollider>().enabled = false;

            GameObject shortHand = AddBox(new Vector3(roomHalfX - 0.10f, 2.19f, -0.8f), new Vector3(0.025f, 0.36f, 0.045f));
            shortHand.GetComponent<MeshRenderer>().sharedMaterial = TriangleShapes.GetMaterial(new Color(0.72f, 0.68f, 0.58f));
            shortHand.GetComponent<BoxCollider>().enabled = false;
        }

        private void BuildNotebook()
        {
            GameObject notebook = Track(new GameObject("Notebook"));
            notebook.transform.SetParent(transform, true);
            notebook.transform.position = new Vector3(2.0f, 0.91f, -0.5f);
            notebook.transform.rotation = Quaternion.identity;
            notebook.tag = "DreamMemory";
            notebook.AddComponent<TriangleNotebook>();
        }

        private void BuildDoor()
        {
            GameObject door = Track(new GameObject("BedroomDoor"));
            door.transform.SetParent(transform, true);
            door.transform.position = new Vector3((DoorGapMinX + DoorGapMaxX) * 0.5f, 1.05f, roomHalfZ - 0.05f);
            door.AddComponent<TriangleDoor>();
        }

        private void BuildCornerPoint()
        {
            GameObject point = Track(new GameObject("TrianglePoint"));
            point.transform.SetParent(transform, true);
            point.transform.position = _cornerLocation;
            TrianglePoint trianglePoint = point.AddComponent<TrianglePoint>();
            trianglePoint.ManifestId = "UpperCornerPoint";
        }

        private void BuildLighting()
        {
            // Ambient moon wash. UE used a SkyLight actor; the equivalent in Unity's
            // built-in pipeline is the scene ambient term.
            RenderSettings.ambientMode = UnityEngine.Rendering.AmbientMode.Trilight;
            RenderSettings.ambientSkyColor = new Color(0.30f, 0.36f, 0.46f);
            RenderSettings.ambientEquatorColor = new Color(0.14f, 0.16f, 0.22f);
            RenderSettings.ambientGroundColor = new Color(0.05f, 0.05f, 0.07f);
            RenderSettings.ambientIntensity = 0.45f;

            // Ceiling fill - sombre, low, slightly warm against the blue moonlight.
            AddLight("CeilingFill", new Vector3(0f, 2.5f, 0f), new Color(0.62f, 0.55f, 0.44f), 1.2f, 9f);

            // Cold glow spilling from the window.
            AddLight("WindowLight", new Vector3(0f, 1.5f, -roomHalfZ - 0.18f), new Color(0.55f, 0.68f, 0.95f), 2.4f, 13f);

            // Fog for corner darkness and depth. UE's ExponentialHeightFog maps onto
            // Unity's built-in exponential-squared fog.
            RenderSettings.fog = true;
            RenderSettings.fogMode = FogMode.ExponentialSquared;
            RenderSettings.fogDensity = 0.0045f;
            RenderSettings.fogColor = new Color(0.06f, 0.07f, 0.09f);
        }

        private void AddLight(string lightName, Vector3 position, Color color, float intensity, float range)
        {
            GameObject lightObject = Track(new GameObject(lightName));
            lightObject.transform.SetParent(transform, true);
            lightObject.transform.position = position;
            Light light = lightObject.AddComponent<Light>();
            light.type = LightType.Point;
            light.color = color;
            light.intensity = intensity;
            light.range = range;
            light.shadows = LightShadows.None;
        }
    }
}
